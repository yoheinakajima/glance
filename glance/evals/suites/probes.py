"""Six procedural probe suites (opt-in): `probe_count`, `probe_count_color`, `probe_spatial`, `probe_largest`,
`probe_stripes`, `probe_text`. Every image is drawn by `glance.lab.probes` (PIL + numpy, no photos), so every
label is exact by construction -- see lab/NOTES.md entry 50. Built by `uv run python -c "from glance.lab
import probes; probes.build()"`; the generator's source manifests and images are read here the same way
`fresh_inat.py` reads a fetched manifest.

- `probe_count`: "How many balls are in `img0`?" -- 1..8.
- `probe_count_color`: "How many RED balls are in `img0`?" -- 0..6.
- `probe_spatial`: yes/no, left/right or above/below the ball is relative to the square.
- `probe_largest`: "Which shape in `img0` is the largest?" -- the colour of the largest of 4 shapes.
- `probe_stripes`: "Which way do the stripes in `img0` run?" -- orientation.
- `probe_text`: "Which word is printed in `img0`?" -- one of a group of six look-alike words.
"""

from __future__ import annotations

import shutil
from types import SimpleNamespace

from ...config import PROJECT_ROOT, Config
from ...logging_utils import read_jsonl
from .base import MANIFEST_DIR, EvalItem, RawItem, SuiteInfo, SuiteSkipped, materialize

IMAGES_ROOT = PROJECT_ROOT / ".cache" / "lab_images_probes"
_BUILD_CMD = 'uv run python -c "from glance.lab import probes; probes.build()"'

COUNT_CRITERIA = {str(i): None for i in range(1, 9)}
COUNT_COLOR_CRITERIA = {str(i): None for i in range(0, 7)}
LARGEST_CRITERIA = {
    "red": "The red shape", "blue": "The blue shape", "green": "The green shape", "yellow": "The yellow shape",
}
STRIPES_CRITERIA = {
    "horizontal": "Horizontal stripes", "vertical": "Vertical stripes",
    "diagonal_rising": "Diagonal stripes rising to the right", "diagonal_falling": "Diagonal stripes falling to the right",
}

_SOURCE = "images drawn by program; labels exact by construction (lab/NOTES.md entry 50)"
_LICENSE = "generated by this project (Apache-2.0)"


def _rows(short_name: str) -> list[dict]:
    source = MANIFEST_DIR / f"probes_{short_name}_source.jsonl"
    rows = read_jsonl(source)
    if not rows:
        raise SuiteSkipped(f"no probes source manifest for `{short_name}`; run `{_BUILD_CMD}`")
    images_dir = IMAGES_ROOT / short_name
    if not (images_dir / rows[0]["file"]).is_file():
        raise SuiteSkipped(f"probes images for `{short_name}` are missing; run `{_BUILD_CMD}` again")
    return rows


def _raw(short_name: str, row: dict, question: dict) -> RawItem:
    src = IMAGES_ROOT / short_name / row["file"]
    return RawItem(
        item_id=row["item_id"], question=question, label=row["label"], ext=".png",
        write_image=lambda dest, src=src: shutil.copyfile(src, dest), meta=row["params"],
    )


def _count(cfg: Config, n: int) -> list[EvalItem]:
    question = {"type": "choice", "instructions": "How many balls are in `img0`?", "criteria": dict(COUNT_CRITERIA)}
    return materialize(cfg, COUNT_INFO, [_raw("count", r, question) for r in _rows("count")], n)


def _count_color(cfg: Config, n: int) -> list[EvalItem]:
    question = {"type": "choice", "instructions": "How many RED balls are in `img0`?", "criteria": dict(COUNT_COLOR_CRITERIA)}
    return materialize(cfg, COUNT_COLOR_INFO, [_raw("count_color", r, question) for r in _rows("count_color")], n)


def _spatial(cfg: Config, n: int) -> list[EvalItem]:
    items = []
    for r in _rows("spatial"):
        question = {"type": "noul", "instructions": r["params"]["question"]}
        items.append(_raw("spatial", r, question))
    return materialize(cfg, SPATIAL_INFO, items, n)


def _largest(cfg: Config, n: int) -> list[EvalItem]:
    question = {"type": "choice", "instructions": "Which shape in `img0` is the largest?", "criteria": dict(LARGEST_CRITERIA)}
    return materialize(cfg, LARGEST_INFO, [_raw("largest", r, question) for r in _rows("largest")], n)


def _stripes(cfg: Config, n: int) -> list[EvalItem]:
    question = {"type": "choice", "instructions": "Which way do the stripes in `img0` run?", "criteria": dict(STRIPES_CRITERIA)}
    return materialize(cfg, STRIPES_INFO, [_raw("stripes", r, question) for r in _rows("stripes")], n)


def _text(cfg: Config, n: int) -> list[EvalItem]:
    items = []
    for r in _rows("text"):
        group = r["params"]["group"]
        question = {"type": "choice", "instructions": "Which word is printed in `img0`?", "criteria": {w: None for w in group}}
        items.append(_raw("text", r, question))
    return materialize(cfg, TEXT_INFO, items, n)


COUNT_INFO = SuiteInfo(name="probe_count", qtype="choice", source=_SOURCE, license=_LICENSE, backends=("siglip", "vlm", "frontier"))
COUNT_COLOR_INFO = SuiteInfo(name="probe_count_color", qtype="choice", source=_SOURCE, license=_LICENSE, backends=("siglip", "vlm", "frontier"))
SPATIAL_INFO = SuiteInfo(name="probe_spatial", qtype="noul", source=_SOURCE, license=_LICENSE, backends=("vlm", "frontier"))
LARGEST_INFO = SuiteInfo(name="probe_largest", qtype="choice", source=_SOURCE, license=_LICENSE, backends=("siglip", "vlm", "frontier"))
STRIPES_INFO = SuiteInfo(name="probe_stripes", qtype="choice", source=_SOURCE, license=_LICENSE, backends=("siglip", "vlm", "frontier"))
TEXT_INFO = SuiteInfo(name="probe_text", qtype="choice", source=_SOURCE, license=_LICENSE, backends=("siglip", "vlm", "frontier"))

MODULES = {
    "probe_count": SimpleNamespace(INFO=COUNT_INFO, build=_count),
    "probe_count_color": SimpleNamespace(INFO=COUNT_COLOR_INFO, build=_count_color),
    "probe_spatial": SimpleNamespace(INFO=SPATIAL_INFO, build=_spatial),
    "probe_largest": SimpleNamespace(INFO=LARGEST_INFO, build=_largest),
    "probe_stripes": SimpleNamespace(INFO=STRIPES_INFO, build=_stripes),
    "probe_text": SimpleNamespace(INFO=TEXT_INFO, build=_text),
}
