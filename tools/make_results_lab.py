"""Writes docs/paper/RESULTS_LAB.md. Every table is generated from the lab's JSON outputs; the prose around them is
fixed text that only states what those tables show.

uv run python tools/make_results_lab.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
J = lambda p: json.loads((ROOT / p).read_text())  # noqa: E731
report, selection, latency = J("lab/REPORT.json"), J("lab/SELECTION.json"), J("lab/LATENCY.json")
extras = {k: J(f"lab/EXTRAS_{k}.json") for k in ("ens4d", "zoom_digits", "independent")}
ref = {k: J(f"lab/REFCHECK_{k}.json") for k in ("ens4d", "ens7")}
SCALES = ["blur", "exposure", "jpeg", "noise", "resolution"]
ORDER = ["independent", "cumulative", "digits", "digitsrev", "zoom_cumulative", "zoom_digits", "zoom_digitsrev",
         "ens2", "ens2r", "ens4d", "ens3", "ens5", "ens7"]
WHAT = {
    "independent": "v0 method: one yes/no statement per level, scale never shown", "cumulative": "scale shown; \"is it step k or higher?\" per threshold",
    "digits": "numbered scale shown; logits over the digit tokens", "digitsrev": "as `digits`, scale listed from highest to lowest",
    "zoom_cumulative": "`cumulative` + magnified centre crop as a second image", "zoom_digits": "`digits` + magnified centre crop",
    "zoom_digitsrev": "`digitsrev` + magnified centre crop", "ens2": "digits + zoom_digits", "ens2r": "zoom_digits + zoom_digitsrev",
    "ens4d": "digits + zoom_digits + digitsrev + zoom_digitsrev", "ens3": "independent + digits + zoom_digits",
    "ens5": "the five stage A readouts", "ens7": "all seven readouts",
}


def ev(scale, key, variant=None):
    e = report[f"{scale}|{key}"]
    return e["variants"][variant or e["chosen"]]["eval"]


def mean(key, field, variant=None):
    return sum(ev(s, key, variant)[field] for s in SCALES) / len(SCALES)


out = ["# Rating scales on a frozen VLM: the score lab (final results)", "",
       "Branch `score-lab`, 2026-09-20. Notebook with hypotheses registered before each experiment: `lab/NOTES.md`. "
       "Method definitions and prompts: `glance/lab/score_methods.py`. Every table below is generated by "
       "`tools/make_results_lab.py` from `lab/REPORT.json`, `lab/SELECTION.json`, `lab/EXTRAS_*.json`, "
       "`lab/REFCHECK_*.json` and `lab/LATENCY.json`; raw logits are in `lab/data/main_stagesAB.jsonl.gz`.", "",
       "## Setup in one paragraph", "",
       "Model: Qwen3-VL-4B-Instruct, float16 on Apple M5 (MPS), no generation, VLM weights frozen (the calibration is the only fitted object). Task: rate an image on a "
       "4-level scale whose levels are described in words. Five synthetic degradation scales (blur, noise, JPEG artifacts, "
       "underexposure, low resolution) on 448 px photos from the Oxford-IIIT Pet test set that no other suite uses; 1,000 "
       "items per scale, 125 per level and split; 500 calibration and 500 test items per scale. Readouts return logits; a "
       "small calibration (at most a 4 x F affine map on the logits, F <= 26) is fit on the calibration split. The method "
       "called the winner was chosen by 5-fold cross-validated NLL inside the calibration split, recorded in "
       "`lab/NOTES.md` (entry 12) and committed before the test split was scored. The test split was scored once.", ""]

out += ["## 1. Selection on the calibration split (the test split was not read)", "",
        "| Rank | Candidate | Forward passes | Mean CV NLL | Mean CV accuracy |", "| --- | --- | --- | --- | --- |"]
ranked = sorted(selection["summary"], key=lambda k: selection["summary"][k]["mean_cv_nll"])
for i, k in enumerate(ranked, 1):
    s = selection["summary"][k]
    out.append(f"| {i} | `{k}` | {s['forward_passes']} | {s['mean_cv_nll']:.4f} | {s['mean_cv_accuracy']:.3f} |")
out += ["", f"Winner at any cost: `{selection['winner_overall']}`. Winner within {selection['budget']} forward passes (the number "
        f"the v0 method uses; not the same latency, see section 9): `{selection['winner_budget']}`.", ""]

out += ["## 2. Test split, every method (n = 500 per scale, scored once)", "",
        "| Method | What it is | Passes | marginal p50 ms (image already cached) | " + " | ".join(SCALES) + " | mean accuracy | mean MAE | mean ECE |",
        "| --- | --- | --- | --- | " + " | ".join("---" for _ in SCALES) + " | --- | --- | --- |"]
for k in ORDER:
    e = report[f"blur|{k}"]
    out.append(f"| `{k}` | {WHAT[k]} | {e['forward_passes']} | {e['latency_ms_p50']:.0f} | "
               + " | ".join(f"{ev(s, k)['accuracy']:.3f}" for s in SCALES)
               + f" | **{mean(k, 'accuracy'):.3f}** | {mean(k, 'mae'):.3f} | {mean(k, 'ece'):.3f} |")
out += ["", "Each method is shown with the calibration chosen for it by cross-validation on the calibration split. The latency "
        "column is the separately measured, uncontended p50 of the readout on the prefix-cached path (`lab/LATENCY.json`); a "
        "combination is the sum of its members. CORRECTION (2026-09-20, `lab/NOTES.md` entry 16): in that benchmark "
        "`independent` and `zoom_cumulative` ran first on each image and paid the image prefill, every other readout found "
        "the prefix cached. The column is therefore the MARGINAL cost of adding a readout, and is not comparable across rows "
        "that did and did not pay the prefill. Section 9 gives the cost of each method on a fresh image.", ""]

out += ["## 3. The two winners against the v0 method, per scale", "",
        "| Scale | Method | Calibration | Accuracy | Within 1 level | MAE (levels) | Spearman | NLL | ECE | ECE floor |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
for s in SCALES:
    for k, variant, label in (("independent", "T", "v0 as shipped (single temperature)"), ("independent", None, "v0 readout, best calibration"),
                              ("ens4d", None, "`ens4d`"), ("ens7", None, "`ens7`")):
        m = ev(s, k, variant)
        name = variant or report[f"{s}|{k}"]["chosen"]
        out.append(f"| {s} | {label} | {name} | {m['accuracy']:.3f} | {m['within_1']:.3f} | {m['mae']:.3f} | {m['spearman']:.3f} | "
                   f"{m['nll']:.3f} | {m['ece']:.3f} | {m['ece_floor']:.3f} |")
v0 = sum(ev(s, "independent", "T")["accuracy"] for s in SCALES) / 5
out += ["", f"Mean accuracy: v0 as shipped {v0:.3f}; v0 readout with its best calibration {mean('independent', 'accuracy'):.3f}; "
        f"`ens4d` {mean('ens4d', 'accuracy'):.3f}; `ens7` {mean('ens7', 'accuracy'):.3f}.", "",
        "Bar fixed before the experiments (`lab/NOTES.md`, entry 1): accuracy >= 0.85, MAE <= 0.25 levels and ECE <= 0.05 on "
        "at least 4 of the 5 scales, for one single method. Scales meeting all three conditions: "
        + "; ".join(f"`{k}`: " + ", ".join(s for s in SCALES if ev(s, k)["accuracy"] >= 0.85 and ev(s, k)["mae"] <= 0.25 and ev(s, k)["ece"] <= 0.05)
                    for k in ("ens4d", "ens7")) + ".", ""]

out += ["## 4. How many labeled examples does the calibration need?", "",
        "Accuracy on the test split when only n labeled calibration items (equal per level) are used; mean and standard "
        "deviation over 20 random draws.", ""]
for key, title in (("ens4d", "`ens4d`, matrix calibration"), ("zoom_digits", "`zoom_digits` (one forward pass), matrix calibration")):
    lc = extras[key]["learning_curve"]
    sizes = sorted({int(n) for c in lc.values() for n in c})
    out += [f"**{title}**", "", "| Scale | " + " | ".join(f"n={n}" for n in sizes) + " |", "| --- | " + " | ".join("---" for _ in sizes) + " |"]
    for s in SCALES:
        out.append(f"| {s} | " + " | ".join(f"{lc[s][str(n)]['accuracy'][0]:.3f} ± {lc[s][str(n)]['accuracy'][1]:.3f}" if str(n) in lc[s] else "-" for n in sizes) + " |")
    out.append("")
out += ["n = 0 is the raw, uncalibrated readout (a combination of readouts has none)."]

xf = extras["ens4d"]["transfer"]
out += ["", "## 5. Is a calibration specific to its scale?", "", "`ens4d`: accuracy on the test split of the column scale when the calibration "
        "was fit on the row scale.", "", "| Fit on | " + " | ".join(SCALES) + " |", "| --- | " + " | ".join("---" for _ in SCALES) + " |"]
for src in SCALES + ["POOLED"]:
    out.append(f"| {src} | " + " | ".join(f"{xf[src][d]:.3f}" for d in SCALES) + " |")

out += ["", "## 6. Reference (uncached) path check", "",
        "The experiments used the prefix-cached path. The first 100 test items of each scale were re-collected without the "
        "cache (`lab/runs/reference_check.jsonl`); the calibration fit on cached logits was applied unchanged to both.", "",
        "| Method | Scale | n | max abs logit diff | median abs logit diff | same prediction | accuracy cached | accuracy reference |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |"]
for k in ("ens4d", "ens7"):
    for s in SCALES:
        r = ref[k][s]
        out.append(f"| `{k}` | {s} | {r['n']} | {r['max_abs_diff']:.3f} | {r['median_abs_diff']:.3f} | {r['same_prediction']:.3f} | "
                   f"{r['accuracy_cached']:.3f} | {r['accuracy_reference']:.3f} |")

out += ["", "## 7. Marginal latency of each readout (cached path, one question, one image)", "",
        "Order within an image: `independent`, `cumulative`, `digits`, `zoom_cumulative`, `zoom_digits`, `digitsrev`, "
        "`zoom_digitsrev`. Only the first one-image readout and the first two-image readout pay a prefill (see the correction "
        "under section 2).", "", "| Readout | p50 ms | paid the image prefill |", "| --- | --- | --- |"]
out += [f"| `{k}` | {v:.0f} | {'yes' if k in ('independent', 'zoom_cumulative') else 'no'} |" for k, v in latency["p50_ms"].items()]
boot = J("lab/BOOTSTRAP.json")
fmt = lambda e: f"{e['point']:.3f} [{e['ci95'][0]:.3f}, {e['ci95'][1]:.3f}]"  # noqa: E731
out += ["", "## 8. Uncertainty: bootstrap 95% intervals", "",
        f"{boot['draws']:,} resamples of the {boot['n_test_per_scale']} test items per scale (`tools/bootstrap_lab.py`, `lab/BOOTSTRAP.json`).", "",
        "| Method | mean accuracy | " + " | ".join(SCALES) + " |", "| --- | --- | " + " | ".join("---" for _ in SCALES) + " |"]
for name, m in boot["methods"].items():
    out.append(f"| `{name}` | {fmt(m['mean'])} | " + " | ".join(fmt(m[s]) for s in SCALES) + " |")
out += ["", "Paired differences in mean accuracy (same resampled items):", "", "| Difference | points | 95% interval |", "| --- | --- | --- |"]
for k, d in boot["paired_differences"].items():
    out.append(f"| {k} | {100 * d['point']:+.1f} | [{100 * d['ci95'][0]:+.1f}, {100 * d['ci95'][1]:+.1f}] |")
below = {k: [sc for sc in SCALES if boot["methods"][k][sc]["point"] >= 0.85 and boot["methods"][k][sc]["ci95"][0] < 0.85] for k in ("ens4d", "ens7")}
out += ["", "Reading: every listed difference excludes zero. The pre-registered bar is met at the point estimates. Among the "
        "scales that meet it, the 95% interval reaches below 0.85 for: "
        + "; ".join(f"`{k}`: {', '.join(v) if v else 'none'}" for k, v in below.items())
        + ". JPEG artifacts is below the bar for every method."]
pack, packed_ref = J("lab/PACKING.json"), J("lab/REFCHECK_packed.json")
out += ["", "## 9. Cost of a rating on a fresh image, and what packing questions saves", "",
        "`glance/lab/pack_bench.py`: prefix cache cleared before every measurement, timed end to end from the image file "
        "(decode, resize, zoom crop, forward passes, readout), uncontended GPU, the first 20 test images of each scale. "
        "\"Packed\" means one prefill of the image with the `digits` and `digitsrev` questions of every scale batched behind it, "
        "and one prefill of image + magnified crop with the two zoom readouts behind it: two prefills in total however many "
        "rating questions are asked. The 25-question rows ask the 25 five-level KADID-style questions of the same lab images "
        "(timing only).", "",
        "| Configuration | images | rating questions answered | p50 ms | p90 ms | p50 ms per question |", "| --- | --- | --- | --- | --- | --- |"]
out += [f"| {name} | {e['images']} | {e['questions']} | {e['p50_ms']:.0f} | {e['p90_ms']:.0f} | {e['p50_ms_per_question']:.0f} |" for name, e in pack.items()]
n_packed = sum(r["n"] for r in packed_ref.values())
out += ["", "Packing changes the batch composition, which perturbs half-precision logits. Check (`lab/REFCHECK_packed.json`): the "
        "calibration fit on the one-readout-at-a-time logits, applied unchanged to the packed logits of the same "
        f"{n_packed} test images:", "",
        "| Scale | n | max abs logit diff | median abs logit diff | same prediction | accuracy one at a time | accuracy packed |",
        "| --- | --- | --- | --- | --- | --- | --- |"]
out += [f"| {s} | {r['n']} | {r['max_abs_diff']:.3f} | {r['median_abs_diff']:.3f} | {r['same_prediction']:.3f} | {r['accuracy_cached']:.3f} | "
        f"{r['accuracy_reference']:.3f} |" for s, r in packed_ref.items()]
(ROOT / "docs/paper/RESULTS_LAB.md").write_text("\n".join(out) + "\n")
print("wrote docs/paper/RESULTS_LAB.md,", len(out), "lines")
