"""Writes docs/paper/RESULTS_ZEROSHOT.md: the headline the owner chose (lab/NOTES.md entry 38): what a frozen OPEN model
does ZERO-SHOT as a general image decision engine, against the same model writing its answer, frontier models zero-shot,
and a dual encoder. Every row in sections 1 to 4 uses no labels of ours. Self-calibration from unlabeled images is its
own row and is never called zero-shot; label-based results live in RESULTS_LAB.md and are only pointed to.
Reads existing result files; a missing one prints "pending", so the document can be regenerated as jobs land.

uv run python tools/make_results_zeroshot.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FRONTIER = {"anthropic/claude-opus-5": "Claude Opus 5", "openai/gpt-5.6": "GPT-5.6", "openrouter/google/gemini-3.1-pro-preview": "Gemini 3.1 Pro"}
LOCAL = "Qwen3-VL-4B + Glance (open, local)"


def load(path):
    f = ROOT / path
    return json.loads(f.read_text()) if f.exists() else None


def acc(e):
    return f"{e['accuracy']:.3f} [{e['ci95'][0]:.3f}, {e['ci95'][1]:.3f}]" if e and "ci95" in e else (f"{e['accuracy']:.3f}" if e else "-")


out = ["# Zero-shot results: a frozen open model as a general image decision engine", "",
       "Branch `score-lab`. Framing set by the owner and recorded in `lab/NOTES.md` entry 38. Every number in sections 1 to 4 is ZERO-SHOT: no labels, "
       "no examples, no fitting on the task. The open model is Qwen3-VL-4B-Instruct (Apache-2.0), frozen, on a laptop; answers are READ from one forward "
       "pass per question (yes/no, pick-one) or four passes (ratings, `ens4d`), never generated. Frontier models got the same question and options and "
       "answered with a constrained pick; their picks are not stored, only right or wrong. Generated by `tools/make_results_zeroshot.py`.", ""]

# 1. public benchmarks
v0 = load("results/v0/analysis/bootstrap_v0.json")
out += ["## 1. Yes/no and pick-one on public benchmarks (may be in every model's training data)", ""]
if v0:
    names = {"pope": "POPE, yes/no about objects", "gqa_yesno": "GQA subset, yes/no", "pets37": "Oxford Pets, pick one of 37 breeds", "caltech101": "Caltech-101, pick one of 101"}
    out += ["| Suite | n | " + LOCAL + " | SigLIP2 (open dual encoder) | Claude Opus 5 | frontier minus local, points |", "| --- | --- | --- | --- | --- | --- |"]
    for key, label in names.items():
        s = v0["suites"][key]
        local = s.get("vlm:statement") or s.get("vlm:independent")
        sig = s.get("siglip:statement") or s.get("siglip:independent")
        gap = s["frontier_minus_local"]
        out.append(f"| {label} | {s['n']} | {acc(local)} | {acc(sig)} | {acc(s['frontier'])} | {gap['points']:+.1f} [{gap['ci95'][0]:+.1f}, {gap['ci95'][1]:+.1f}] |")
    g = v0["mean gap, yes/no and choice suites only (no blur_ladder)"]
    out += ["", f"Mean gap over these four suites: {g['points']:.1f} points [{g['ci95'][0]:.1f}, {g['ci95'][1]:.1f}] in the frontier model's favour. Local answers here are "
            "uncalibrated reads (argmax); one frontier model, one run.", ""]
else:
    out += ["Pending.", ""]

# 2. fresh photos
out += ["## 2. Photos no model can have seen (taken after every model's release; labels made by nobody on this project)", ""]
for path, title, yes_key, choice_key in (("results/lab/fresh_commons.json", "Wikimedia Commons, 131 photos, labels from structured \"depicts\" statements", "fresh_yesno", "fresh_choice"),
                                         ("results/lab/fresh_inat.json", "iNaturalist, 200 photos, labels from research-grade community identifications", "inat_yesno", "inat_choice")):
    d = load(path)
    out += [f"**{title}.**", ""]
    if not d:
        out += ["Pending (local run queued; frontier runs need the owner's one-paste commands).", ""]
        continue
    yes, choice = d["suites"][yes_key], d["suites"][choice_key]
    out += ["| System | yes/no | n | pick-one | n |", "| --- | --- | --- | --- | --- |"]
    rows = [(LOCAL, yes.get("vlm:statement"), choice.get("vlm:independent")), ("SigLIP2 (open dual encoder)", None, choice.get("siglip:independent"))]
    rows += [(name, yes.get(key), choice.get(key)) for key, name in FRONTIER.items() if key in yes or key in choice]
    for name, y, c in rows:
        out.append(f"| {name} | {acc(y)} | {y['n'] if y else '-'} | {acc(c)} | {c['n'] if c else '-'} |")
    out += ["", "The frontier models were scored on the test half only (their n is smaller); intervals overlap everywhere.", ""]

# 3. ratings
h2h, lf = load("results/lab/frontier_head_to_head.json"), load("results/lab/label_free_test.json")
out += ["## 3. Ratings against a rubric in words, zero-shot (five synthetic 4-level scales, same 1,000 held-out images)", ""]
if h2h:
    scales = ["blur", "exposure", "jpeg", "noise", "resolution"]
    out += ["| System | " + " | ".join(scales) + " | mean exact-level accuracy |", "| --- | " + " | ".join("---" for _ in scales) + " | --- |"]
    for run in h2h["runs"].values():
        out.append(f"| {FRONTIER.get(run['model'], run['model'])}, written pick | " + " | ".join(f"{run['accuracy'][s]:.3f}" for s in scales) + f" | **{run['mean_accuracy']:.3f}** |")
    for key, label in (("v0 readout as shipped (single temperature), 0 rubric labels", "Qwen3-VL-4B, v0 readout (one yes/no per level)"),
                       ("+ Glance ens4d, 0 labels", LOCAL + ", `ens4d`")):
        e = h2h["local"][key]
        out.append(f"| {label} | " + " | ".join(f"{e['accuracy'][s]:.3f}" for s in scales) + f" | **{e['mean_accuracy']:.3f}** |")
    out += ["", "Chance is 0.250. Paired differences with intervals are in `results/lab/frontier_head_to_head.md`: the open model is level with Opus 5 and GPT-5.6 "
            "and 8 points behind Gemini 3.1 Pro."]
    if lf:
        raw = lf["raw (0 labels, no pool)"]
        out += [f"Exact level is a hard target zero-shot because where a rubric draws its boundaries is a convention: on the full test split the open model is "
                f"exactly right on {raw['accuracy']:.3f} of images and within one level on {raw['within_1']:.3f} (mean error {raw['mae']:.2f} levels). "
                "Frontier picks are not stored, so their within-one figure is unknown.", ""]
        out += ["**Zero labels, but not zero-shot: self-calibration from unlabeled images of the rubric** (`glance fit --unlabeled`; the readout's bias is removed "
                "by z-scoring each member over a pool of unlabeled images; `lab/NOTES.md` entry 26):", "",
                "| Unlabeled images seen | exact-level accuracy | within one level |", "| --- | --- | --- |"]
        for key, label in (("raw (0 labels, no pool)", "0 (zero-shot)"), ("BCz, pool = 16 unlabeled (20 draws)", "16"), ("BCz, pool = 32 unlabeled (20 draws)", "32"),
                           ("BCz, pool = 64 unlabeled (20 draws)", "64"), ("BCz, pool = all 500 unlabeled", "500"),
                           ("BCz, unbalanced pool of 100 (70% one level)", "100, badly unbalanced (70% one level)")):
            out.append(f"| {label} | {lf[key]['accuracy']:.3f} | {lf[key]['within_1']:.3f} |")
        out += ["", "With the full unlabeled pool the open model is ahead of all three frontier models' zero-shot picks on the same 1,000 images (paired: +5.2 points "
                "[+1.3, +9.3] over Gemini 3.1 Pro, `results/lab/frontier_head_to_head.md`). Sixteen unlabeled images already give most of that gain; that row is "
                "on the full test split and was not tested pairwise against the frontier models. The pool has to cover the range of the rubric: a badly "
                "unbalanced pool gives back part of the gain.", ""]
    kadid = load("results/lab/loro_kadid.json")
    if kadid:
        k = {name: e for name, e in kadid.items()}
        raw = next((e for n, e in k.items() if n.lower().startswith("raw")), None)
        if raw:
            out += [f"On KADID-10k (23 distortion types at 5 severity levels, human-scored, chance 0.200) the zero-shot read is weak: {raw['accuracy']:.3f} exact, "
                    f"{raw['within_1']:.3f} within one level (`results/lab/loro_kadid.md`). Zero-shot rating of fine severity levels is NOT solved.", ""]
else:
    out += ["Pending.", ""]

# 4. reading vs writing, same model
gen, genacc = load("lab/GENBENCH.json"), load("results/lab/gen_accuracy.json")
out += ["## 4. The same open model, reading the answer against writing it as structured output", ""]
if gen:
    out += ["| Request (one image) | write JSON, median ms | read, median ms | speed-up | written and read answers agree |", "| --- | --- | --- | --- | --- |"]
    for name, e in gen.items():
        out.append(f"| {name} | {e['write_p50_ms']:.0f} | {e['read_fast2_p50_ms']:.0f} | {e['speedup_vs_write_fast2']:.1f}x | {e['agreement_with_read_on_valid_fields']:.0%} |")
    out += ["", "Reads here use the two-pass `fast2` rating readout; 40 images, one laptop, GPU otherwise idle (`lab/GENBENCH.md`)."]
out += ["Accuracy of the written answers on the same labeled items (E11, `lab/NOTES.md` entry 32): "
        + ("see `results/lab/gen_accuracy.md`." if genacc else "pending (collection queued)."), ""]

# 5. cost
cost, measured = load("results/lab/cost_model.json"), load("results/lab/frontier_cost_measured.json")
out += ["## 5. Speed and cost per 1,000 answers", ""]
if cost:
    lo = min(r["electricity_usd"][0] for r in cost["local"].values())
    hi = max(r["cloud_gpu_usd"][1] for r in cost["local"].values())
    out += [f"Open model, self-hosted: ${lo:.3f} (electricity, several rubrics per image) to ${hi:.2f} (rented cloud GPU, one rubric per image) per 1,000 ratings; "
            "arithmetic on measured seconds and stated assumptions (`results/lab/cost_model.md`)."]
if measured:
    got = [r for r in measured if r["usd_per_1000_calls"] is not None]
    out += ["Frontier APIs, measured on the owner's runs: " + "; ".join(f"{FRONTIER.get(r['model'], r['model'])} ${r['usd_per_1000_calls']:.2f} per 1,000, "
            f"{r['median_latency_ms'] / 1000:.1f} s median ({r['task'].split(',')[0]})" for r in got) + ". The open model answers one rating in 1.1 s "
            "and 0.34 to 0.58 s per rating when several rubrics share an image.", ""]

# 6. scaling, 7. pointers
scaling = load("results/lab/scaling.json")
out += ["## 6. Does zero-shot improve with model size? (E15, Qwen3-VL 2B / 4B / 8B, identical prompts and settings)", "",
        "See `results/lab/scaling.md`." if scaling else "Pending: registered in `lab/NOTES.md` entry 38 with a prediction that can fail (8B stays below 0.70 exact on the "
        "lab scales zero-shot). The 8B model must run alone on this 32 GB machine.", "",
        "## 7. If you do have examples (a caveat, not the headline)", "",
        "With 32 labeled images per rubric the same frozen model reaches 0.857 on the lab scales (`docs/paper/RESULTS_LAB.md`); a fitted readout on its hidden "
        "state goes higher still but needs more labels (`lab/READOUT_LADDER.md`). Classical hand-built features beat both on low-level artifacts when labels are "
        "plentiful (`docs/paper/RESULTS_COMPARISONS.md`).", ""]
(ROOT / "docs/paper/RESULTS_ZEROSHOT.md").write_text("\n".join(out) + "\n")
print("wrote docs/paper/RESULTS_ZEROSHOT.md,", len(out), "lines")
