"""Writes docs/paper/RESULTS_GENERALIZATION.md from lab/KADID_REPORT.json and lab/DISTORT25_REPORT.json (either may be
missing while collection is running). Tables and the verdicts on the pre-registered hypotheses (lab/NOTES.md entry 14)
are computed; the prose only states what they show.

uv run python -m glance.lab.bench_report --bench kadid --in lab/runs/kadid.jsonl --out lab/KADID_REPORT --separate mean_shift,contrast_change
uv run python -m glance.lab.bench_report --bench distort25 --in lab/runs/distort25.jsonl --out lab/DISTORT25_REPORT
uv run python tools/make_results_generalization.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
BENCHES = {
    "distort25": ("lab/DISTORT25_REPORT.json", "`distort25`: 25 distortions x 5 levels rebuilt on license-clean photos (Oxford-IIIT Pet train "
                  "split, 300 items per distortion, 150 calibration / 150 test, no photo shared with the lab scales)"),
    "kadid": ("lab/KADID_REPORT.json", "KADID-10k: 81 reference images x 25 distortions x 5 levels with human DMOS, evaluation only, split by "
              "reference image (41 calibration / 40 test references, 205 / 200 items per distortion)"),
}
SEPARATE = {"kadid": ["mean_shift", "contrast_change"], "distort25": []}
LAB_ENS4D = 0.867


def verdict(ok: bool | None) -> str:
    return "not evaluable yet" if ok is None else ("SUPPORTED" if ok else "NOT SUPPORTED")


out = ["# Does the rating method generalize? Fixed method, 25 distortion types, human scores", "",
       "Branch `score-lab`. Registered before any of this data existed: `lab/NOTES.md` entries 14, 15 and 15b (method `ens4d` "
       "exactly as selected in the score lab, matrix calibration per distortion, ONE generic question wording for all 25 "
       "distortions, baselines, hypotheses H7 to H9, and the report definition). Nothing was re-selected or re-worded after "
       "seeing results. Tables are generated by `tools/make_results_generalization.py` from `glance/lab/bench_report.py` output.", "",
       "Question asked for every distortion: \"How strong is the <one-line description> in `img0`?\" with the levels "
       "Barely noticeable / Slight / Moderate / Strong / Very strong. Model: Qwen3-VL-4B-Instruct, frozen. "
       "In result rows, `ens4d` is \"Qwen3-VL-4B + Glance\".", ""]

loaded = {}
for bench, (path, title) in BENCHES.items():
    file = ROOT / path
    if not file.exists():
        out += [f"## {title}", "", "Collection not finished; no numbers yet.", ""]
        continue
    report = json.loads(file.read_text())
    loaded[bench] = report
    summary, per = report["summary"], report["per_scale"]
    has_dmos = "mean_srcc_vs_dmos" in summary.get("ens4d", {})
    out += [f"## {title}", ""]
    head = ["Method", "distortions in the mean", "accuracy", "accuracy on the most confident 80%", "within one level", "MAE (levels)",
            "pooled ECE (floor)"] + (["mean per-type SRCC with DMOS", "ceiling: the true level's SRCC", "overall SRCC, type-aware", "overall PLCC, type-aware"] if has_dmos else [])
    out += ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    names = {"ens4d": "Qwen3-VL-4B + Glance (`ens4d`)", "zoom_digits": "one pass: `zoom_digits`", "digits": "one pass: `digits`",
             "independent": "v0 readout, best calibration", "independent (as shipped)": "v0 readout as shipped"}
    for key, label in names.items():
        if key not in summary:
            continue
        e = summary[key]
        cells = [label, e["scales"], f"{e['accuracy']:.3f}", f"{e['accuracy_at_80']:.3f}", f"{e['within_1']:.3f}", f"{e['mae']:.3f}",
                 f"{e['pooled_ece']:.3f} ({e['pooled_ece_floor']:.3f})"]
        if has_dmos:
            cells += [f"{e['mean_srcc_vs_dmos']:.3f}", f"{e['mean_srcc_true_level_vs_dmos']:.3f}", f"{e['overall_srcc_type_aware']:.3f}",
                      f"{e['overall_plcc_type_aware']:.3f}"]
        out.append("| " + " | ".join(str(c) for c in cells) + " |")
    if SEPARATE[bench]:
        out += ["", "Excluded from the means above and shown in the per-distortion table: " + ", ".join(f"`{s}`" for s in SEPARATE[bench])
                + ". Their five levels are not a severity order (`lab/NOTES.md` entry 15); decided before any model output."]
    if has_dmos:
        out += ["", "SRCC and PLCC here are TYPE-AWARE: the question names the distortion, and a per-distortion monotone map from the "
                "expected level to DMOS is fit on the calibration references. They are not comparable with blind image-quality "
                "numbers in the literature, which do not know the distortion type. The ceiling column is what a perfect level "
                "predictor would reach, because DMOS also varies with image content inside a level."]
    lead = per["ens4d"]
    others = [k for k in ("independent", "independent (as shipped)", "zoom_digits") if k in per]
    out += ["", "| Distortion | n fit | n test | accuracy | within one | MAE | ECE (floor) | " + ("SRCC with DMOS | " if has_dmos else "")
            + " | ".join(f"accuracy, {names[k]}" for k in others) + " |",
            "| --- | --- | --- | --- | --- | --- | --- | " + ("--- | " if has_dmos else "") + " | ".join("---" for _ in others) + " |"]
    for scale, m in sorted(lead.items(), key=lambda kv: -kv[1]["accuracy"]):
        flag = " (not a severity scale)" if scale in SEPARATE[bench] else ""
        out.append(f"| {scale}{flag} | {m['n_fit']} | {m['n']} | {m['accuracy']:.3f} | {m['within_1']:.3f} | {m['mae']:.3f} | "
                   f"{m['ece']:.3f} ({m['ece_floor']:.3f}) | " + (f"{m['srcc_vs_dmos']:.3f} | " if has_dmos else "")
                   + " | ".join(f"{per[k][scale]['accuracy']:.3f}" if scale in per[k] else "-" for k in others) + " |")
    out.append("")

def load(path):
    f = ROOT / path
    return json.loads(f.read_text()) if f.exists() else None


cmp_ = load("results/lab/kadid_vlm_vs_classical.json")
if cmp_:
    c, v = cmp_["classical"], cmp_["vlm_ens4d"]
    out += ["## KADID-10k: the VLM against classical features with the same labels (23 severity distortions)", "",
            "| System | about 30 labels per distortion | all 205 labels | within one level (205) | MAE (205) | per-type Spearman with human DMOS (205) |",
            "| --- | --- | --- | --- | --- | --- |",
            f"| 29 classical no-reference features + logistic regression | {c['accuracy_small_n']:.3f} | **{c['accuracy']:.3f}** | {c['within_1']:.3f} | {c['mae']:.3f} | {c['spearman_dmos']:.3f} |",
            f"| Qwen3-VL-4B + Glance (`ens4d`) | **{v['accuracy_by_labels']['30']:.3f}** | {v['accuracy']:.3f} | {v['within_1']:.3f} | {v['mae']:.3f} | **{v['spearman_dmos']:.3f}** |", "",
            f"With 60 and 100 labels the VLM reaches {v['accuracy_by_labels']['60']:.3f} and {v['accuracy_by_labels']['100']:.3f}. With all labels it has the higher exact "
            f"accuracy on {len(cmp_['vlm_wins'])} of {cmp_['n_distortions']} distortions: " + ", ".join(f"`{s}`" for s in cmp_["vlm_wins"]) + ". "
            "Reading: on exact severity levels, hand-built features win once a couple of hundred labels exist; the VLM is ahead with few labels, "
            "ranks images more like people do, and is ahead on the distortions that are structural rather than statistical.", ""]
loro = load("results/lab/loro_kadid.json")
if loro:
    out += ["## KADID-10k: can a rating rubric work with NO labels of its own? (leave one distortion out; `lab/NOTES.md` entry 26)", "",
            "| Setting | labels from the target distortion | mean accuracy | within one level |", "| --- | --- | --- | --- |"]
    out += [f"| {k} | {'about 205' if k.startswith('per-rubric') else '0'} | {e['accuracy']:.3f} | {e['within_1']:.3f} |" for k, e in loro.items()]
    out += ["", "A map learned on 22 other distortions barely helps a distortion it has not seen (calibrations are rubric-specific, as on the lab "
            "scales). Removing the readout's bias with unlabeled images of the target helps more, and the two together recover about half of the "
            "distance between nothing and a labeled fit.", ""]

out += ["## Verdicts on the registered hypotheses", ""]
rows = []
for bench, report in loaded.items():
    s = report["summary"]
    e = s.get("ens4d")
    base = s.get("independent")
    rows.append((f"H7 on `{bench}`: `ens4d` beats the v0 readout with its best calibration on mean accuracy",
                 None if not (e and base) else e["accuracy"] > base["accuracy"],
                 "" if not (e and base) else f"{e['accuracy']:.3f} vs {base['accuracy']:.3f}"))
    if e:
        rows.append((f"H8 on `{bench}`: accuracy clearly below the lab's {LAB_ENS4D}", e["accuracy"] < LAB_ENS4D, f"{e['accuracy']:.3f}"))
        rows.append((f"H8 on `{bench}`: exact accuracy >= 0.70", e["accuracy"] >= 0.70, f"{e['accuracy']:.3f}"))
        rows.append((f"H8 on `{bench}`: within one level >= 0.97", e["within_1"] >= 0.97, f"{e['within_1']:.3f}"))
        rows.append((f"H8 on `{bench}`: MAE <= 0.40 levels", e["mae"] <= 0.40, f"{e['mae']:.3f}"))
        rows.append((f"H8 on `{bench}`: ECE <= 0.05 on at least 20 distortions (criterion flawed, see entry 15b: the sampling floor at "
                     f"this test size is above 0.05)", e["scales_ece_le_0.05"] >= 20, f"{e['scales_ece_le_0.05']} of {e['scales']}"))
        if "mean_srcc_vs_dmos" in e:
            rows.append((f"H9 on `{bench}`: mean per-type SRCC with DMOS >= 0.85", e["mean_srcc_vs_dmos"] >= 0.85, f"{e['mean_srcc_vs_dmos']:.3f}"))
out += ["| Hypothesis (registered in `lab/NOTES.md` entry 14) | Verdict | Measured |", "| --- | --- | --- |"]
out += [f"| {text} | {verdict(ok)} | {measured} |" for text, ok, measured in rows] or ["| (no data yet) | | |"]
(ROOT / "docs/paper/RESULTS_GENERALIZATION.md").write_text("\n".join(out) + "\n")
print("wrote docs/paper/RESULTS_GENERALIZATION.md,", len(out), "lines;", "benches with data:", list(loaded) or "none")
